package com.smartautomation.testautomation.service;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.smartautomation.testautomation.model.ExecutionTestResult;
import com.smartautomation.testautomation.model.JestRunResult;
import com.smartautomation.testautomation.model.NodeExecutionResult;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;

@Service
public class JestExecutionService {

    private static final Logger LOGGER = LoggerFactory.getLogger(JestExecutionService.class);

    /** Required JSON keys in a Jest report. At least one must be present. */
    private static final List<String> JEST_REPORT_KEYS = List.of(
            "\"numTotalTests\"", "\"numFailedTestSuites\"", "\"testResults\"", "\"numTotalTestSuites\""
    );

    private final NodeBridgeService nodeBridgeService;
    private final ObjectMapper objectMapper = new ObjectMapper();

    @Value("${jest.execution.timeout-seconds:45}")
    private long timeoutSeconds;

    public JestExecutionService(NodeBridgeService nodeBridgeService) {
        this.nodeBridgeService = nodeBridgeService;
    }

    public ExecutionTestResult executerTest(String testFilePath) {
        LOGGER.info("Executing generated test via Jest: {}", testFilePath);

        // ── 1. Pre-execution syntax validation via node --check ─────────────────
        NodeExecutionResult syntaxCheck = verifierSyntaxe(testFilePath);
        if (!syntaxCheck.isSuccess() && !syntaxCheck.isTimedOut()) {
            String syntaxError = syntaxCheck.getStderr();
            if (syntaxError != null && !syntaxError.isBlank()) {
                LOGGER.warn("Compilation/syntax error in {}: {}", testFilePath, tronquer(syntaxError));
                return ExecutionTestResult.erreurCompilation(
                        "Generated test does not compile: " + tronquer(syntaxError),
                        syntaxError
                );
            }
        }

        // ── 2. Jest execution with --json ────────────────────────────────────────
        NodeExecutionResult processResult = nodeBridgeService.runScriptAtPathWithTimeout(
                "node_modules/jest/bin/jest.js",
                timeoutSeconds,
                testFilePath, "--json", "--ci", "--forceExit"
        );

        // ── 3. Jest output parsing ─────────────────────────────────────────
        JestRunResult jestResult = parserSortieJest(processResult.getStdout(), processResult.getStderr());
        if (jestResult != null) {
            LOGGER.info("Jest result for {}: {}/{} tests passed (success={}, timedOut={})",
                    testFilePath,
                    jestResult.getTestsReussis(),
                    jestResult.getTotalTests(),
                    jestResult.isSuccess(),
                    processResult.isTimedOut());
            return ExecutionTestResult.depuisJest(jestResult);
        }

        // ── 4. Timeout case ─────────────────────────────────────────────────────
        if (processResult.isTimedOut()) {
            LOGGER.warn("Timeout during test execution {} (possible infinite loop generated by LLM)", testFilePath);
            return ExecutionTestResult.erreurTechnique(
                    "Timeout exceeded (" + timeoutSeconds + "s): generated test did not complete in time");
        }

        // ── 5. No usable output ───────────────────────────────────────────
        String stdout = processResult.getStdout();
        String stderr = processResult.getStderr();

        if (stdout == null || stdout.isBlank()) {
            LOGGER.error("No JSON output received from Jest for {}: {}", testFilePath, stderr);
            return ExecutionTestResult.erreurTechnique(
                    "Jest produced no usable output. stderr: " + tronquer(stderr));
        }

        LOGGER.error("Unable to parse Jest JSON output for {}", testFilePath);
        // Provide the first significant error line from stderr if available
        String detail = extrairePremiereErreur(stderr);
        if (detail == null || detail.isBlank()) {
            detail = tronquer(stdout);
        }
        return ExecutionTestResult.erreurTechnique(
                "Jest output unreadable (not valid JSON): " + detail);
    }

    // ────────────────────────────────────────────────────────────────────────────
    //  Package-private pour les tests unitaires
    // ────────────────────────────────────────────────────────────────────────────

    JestRunResult parserSortieJest(String stdout, String stderr) {
        JestRunResult depuisStdout = parserJsonJest(extraireJsonJest(stdout));
        if (depuisStdout != null) {
            return depuisStdout;
        }
        return parserJsonJest(extraireJsonJest(stderr));
    }

    /**
     * Extracts the first balanced JSON block that corresponds to a Jest report.
     *
     * <p>Unlike the previous version that took the first '{' and the last '}',
     * this method processes the string character by character, handling:
     * <ul>
     *   <li>quoted strings (single, double, backtick) and escape sequences;</li>
     *   <li>brace nesting to correctly delimit the JSON block;</li>
     *   <li>validation that the found block contains Jest-specific keys.</li>
     * </ul>
     */
    String extraireJsonJest(String output) {
        if (output == null || output.isBlank()) {
            return null;
        }

        // Remove potential BOM
        String text = output.stripLeading();
        if (text.startsWith("\uFEFF")) {
            text = text.substring(1);
        }

        List<String> candidates = extraireBlocs(text);

        // Validate each candidate: it must contain at least one known Jest key
        for (String candidate : candidates) {
            for (String key : JEST_REPORT_KEYS) {
                if (candidate.contains(key)) {
                    return candidate;
                }
            }
        }

        // No valid candidate → return null
        return null;
    }

    /**
     * Extracts all top-level JSON blocks (balanced braces) present in {@code text}.
     * Handles quoted strings and escape sequences.
     */
    List<String> extraireBlocs(String text) {
        List<String> blocks = new ArrayList<>();
        int n = text.length();
        int i = 0;
        while (i < n) {
            // Look for next '{'
            while (i < n && text.charAt(i) != '{') {
                i++;
            }
            if (i >= n) break;

            int start = i;
            int depth = 0;
            boolean inString = false;
            char quoteChar = 0;

            while (i < n) {
                char c = text.charAt(i);

                if (inString) {
                    if (c == '\\') {
                        i += 2; // skip escaped character
                        continue;
                    }
                    if (c == quoteChar) {
                        inString = false;
                    }
                } else {
                    if (c == '"' || c == '\'' || c == '`') {
                        inString = true;
                        quoteChar = c;
                    } else if (c == '{') {
                        depth++;
                    } else if (c == '}') {
                        depth--;
                        if (depth == 0) {
                            blocks.add(text.substring(start, i + 1));
                            i++;
                            break;
                        }
                    }
                }
                i++;
            }
            // If depth > 0 here, the block is malformed → advance just after the initial '{'
            if (depth > 0) {
                i = start + 1;
            }
        }
        return blocks;
    }

    // ────────────────────────────────────────────────────────────────────────────
    //  Méthodes privées
    // ────────────────────────────────────────────────────────────────────────────

    private JestRunResult parserJsonJest(String json) {
        if (json == null || json.isBlank()) {
            return null;
        }
        try {
            JestRunResult result = objectMapper.readValue(json, JestRunResult.class);
            enrichirComptages(result);
            return result;
        } catch (JsonProcessingException e) {
            LOGGER.debug("Jest stream not parsable as JSON: {}", e.getMessage());
            return null;
        }
    }

    /**
     * Runs {@code node --check <path>} to detect JS syntax errors
     * without executing the file.
     */
    private NodeExecutionResult verifierSyntaxe(String testFilePath) {
        return nodeBridgeService.runScriptAtPathWithTimeout(
                "--check", 10,
                testFilePath
        );
    }

    /**
     * Enriches Jest result counts:
     * <ol>
     *   <li>If test counters are 0 but there are assertionResults, recalculate from assertions.</li>
     *   <li>If suites failed (compilation/runtime error) without assertions, count each failed suite as 1 failed test.</li>
     *   <li>Extracts suite-level error messages (testSuiteFailureMessage) for module loading errors.</li>
     * </ol>
     */
    private void enrichirComptages(JestRunResult result) {
        int passedFromAssertions = compterAssertionsParStatut(result, "passed");
        int totalFromAssertions = compterTotalAssertions(result);

        if (result.getTestsReussis() == 0 && passedFromAssertions > 0) {
            result.setTestsReussis(passedFromAssertions);
        }
        if (result.getTotalTests() == 0 && totalFromAssertions > 0) {
            result.setTotalTests(totalFromAssertions);
        }

        // Suites in compilation/runtime error without tests (totalTests still 0)
        int suiteErrors = result.getSuiteEchouees() + result.getSuiteErreursRuntime();
        if (result.getTotalTests() == 0 && suiteErrors > 0) {
            result.setTotalTests(suiteErrors);
            result.setTestsEchoues(suiteErrors);
        }

        // Extract and store suite-level error messages
        extraireMessagesErreurSuite(result);
    }

    /**
     * Extracts suite-level error messages (ex: "Cannot find module")
     * and stores them for use in the error report.
     */
    private void extraireMessagesErreurSuite(JestRunResult result) {
        if (result.getTestResults() == null) {
            return;
        }
        for (JestRunResult.TestSuiteResult suite : result.getTestResults()) {
            if (suite.getMessage() != null && !suite.getMessage().isBlank()) {
                // Suite message is already available via suite.getMessage()
                // It will be used by MultiTypeTestExecutionService for the report
                LOGGER.debug("Suite error message detected: {}", suite.getMessage());
            }
        }
    }

    private int compterAssertionsParStatut(JestRunResult result, String expectedStatus) {
        if (result.getTestResults() == null) {
            return 0;
        }
        int count = 0;
        for (JestRunResult.TestSuiteResult suite : result.getTestResults()) {
            if (suite.getAssertionResults() == null) {
                continue;
            }
            for (JestRunResult.AssertionResult assertion : suite.getAssertionResults()) {
                if (expectedStatus.equals(assertion.getStatus())) {
                    count++;
                }
            }
        }
        return count;
    }

    private int compterTotalAssertions(JestRunResult result) {
        if (result.getTestResults() == null) {
            return 0;
        }
        int count = 0;
        for (JestRunResult.TestSuiteResult suite : result.getTestResults()) {
            if (suite.getAssertionResults() != null) {
                count += suite.getAssertionResults().size();
            }
        }
        return count;
    }

    /**
     * Extracts the first significant error line from stderr stream (non-empty,
     * not starting with {@code at } which are stack trace lines).
     */
    private String extrairePremiereErreur(String stderr) {
        if (stderr == null || stderr.isBlank()) return null;
        for (String line : stderr.split("\\R")) {
            String l = line.strip();
            if (!l.isEmpty() && !l.startsWith("at ") && !l.startsWith("●")
                    && !l.startsWith("PASS") && !l.startsWith("FAIL")) {
                return tronquer(l);
            }
        }
        return null;
    }

    private String tronquer(String text) {
        if (text == null) return "";
        return text.length() > 500 ? text.substring(0, 500) + "..." : text;
    }
}
